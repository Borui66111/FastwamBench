#!/usr/bin/env python
"""[fastbench] Gate 13 CPU-only audit: recompute every quoted number from the bundle.

Reads only `evidence/gate13_bundle/` (committed, ~700 KB, text). No GPU, no
`results/`, no checkpoints, no RGB frames. Regenerates the canonical tables and
prints PASS/FAIL for the validity checks a reviewer would want:

  1. pair counts      -- every (task, H, seed, init_state) has both arms, once
  2. pre-intervention -- control and disturb action streams are bit-identical
     equality           before the intervention (max |L1| == 0)
  3. stale contract   -- stale_action_steps == H in every disturbed episode, and
                         0 in every control episode
  4. PSNR pairing     -- per-pair deltas at a matched lag, with a cluster
                         bootstrap CI resampling INIT STATES (not episodes)

Two numbers the earlier reports got wrong are computed here from the same rows
so the retraction is checkable: the episode-mean PSNR delta (dilution confound)
and the per-episode clip average (the "2.4x" confound).

Usage
-----
  python scripts_setup/gate13_audit.py
  python scripts_setup/gate13_audit.py --bundle evidence/gate13_bundle --out evidence/gate13_canonical.md
Exit code is 0 only if every PASS/FAIL check passes.
"""
import argparse
import json
import math
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANONICAL_PSNR_GATE = "gate13_psnr_clip"
SUCCESS_GATE = "gate13_main"


# ---------------------------------------------------------------- statistics
def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    s = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - s) / d, (c + s) / d)


def mcnemar_exact(b, c):
    """Two-sided exact McNemar on discordant pair counts b and c."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    tail = sum(math.comb(n, i) for i in range(0, k + 1)) / (2.0 ** n)
    return min(1.0, 2 * tail)


def cluster_bootstrap(values_by_cluster, reps=10000, seed=0):
    """95% percentile CI for the mean, resampling CLUSTERS (init states)."""
    keys = sorted(values_by_cluster)
    if len(keys) < 2:
        return (float("nan"), float("nan"))
    rng = random.Random(seed)
    means = []
    for _ in range(reps):
        sample = [rng.choice(keys) for _ in keys]
        pool = [v for k in sample for v in values_by_cluster[k]]
        means.append(sum(pool) / len(pool))
    means.sort()
    lo = means[int(0.025 * len(means))]
    hi = means[int(0.975 * len(means)) - 1]
    return (lo, hi)


def db_to_mse(db):
    """Invert the harness convention PSNR = 10*log10(255^2 / MSE)."""
    return (255.0 ** 2) / (10.0 ** (db / 10.0))


# ------------------------------------------------------------------- loading
def load_jsonl(path):
    if not path.exists():
        return []
    return [json.loads(line) for line in open(path) if line.strip()]


def lag_map(fp):
    if isinstance(fp, dict):
        return {int(k): float(v) for k, v in fp.items()}
    if isinstance(fp, list):
        return {i: float(v) for i, v in enumerate(fp)}
    return {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", default=str(ROOT / "evidence" / "gate13_bundle"))
    ap.add_argument("--out", default=str(ROOT / "evidence" / "gate13_canonical.md"))
    ap.add_argument("--world-step", type=int, default=40)
    ap.add_argument("--video-stride", type=int, default=4)
    args = ap.parse_args()

    bundle = Path(args.bundle)
    manifest = json.loads((bundle / "manifest.json").read_text())
    world_step = args.world_step
    stride = args.video_stride
    checks = []
    lines = []
    w = lines.append

    w("# Gate 13 — canonical tables, recomputed from the committed bundle")
    w("")
    w(f"Generated by `scripts_setup/gate13_audit.py` from `{bundle.relative_to(ROOT) if bundle.is_relative_to(ROOT) else bundle}`.")
    w("CPU only; no GPU, no `results/`, no checkpoints. Every number quoted in")
    w("`README.md`, `evidence/gate13_HOW_TO_REVIEW.md` and")
    w("`evidence/gate13_commitment_cost.md` must match a row below.")
    w("")
    prov = manifest.get("provenance", {})
    w("**Provenance.** repo `%s` (%s%s); FastWAM `%s`; LIBERO-Safety `%s`; "
      "controller config `osc_pose.json` sha256 `%s`." % (
          (prov.get("repo_sha") or "?")[:12],
          prov.get("repo_branch") or "?",
          ", dirty tree" if prov.get("repo_dirty") else "",
          (prov.get("fastwam_sha") or "?")[:12],
          (prov.get("libero_safety_sha") or "?")[:12],
          (prov.get("controller_config_sha256") or "?")[:16] + "...",
      ))
    w("")

    # ---------------------------------------------------------------- success
    eps = load_jsonl(bundle / f"episodes_{SUCCESS_GATE}.jsonl")
    if not eps:
        print(f"FATAL: no episodes_{SUCCESS_GATE}.jsonl in bundle")
        return 2

    cells = defaultdict(dict)  # (task,H,seed) -> {arm: {init_state: row}}
    for e in eps:
        cells[(e["task"], e["H"], e["seed"])].setdefault(e["arm"], {})[e["init_state_idx"]] = e

    # check 1: pair counts
    bad_pairs = []
    n_pairs = 0
    for key, arms in sorted(cells.items()):
        if set(arms) != {"control", "disturb"}:
            bad_pairs.append((key, sorted(arms)))
            continue
        ci, di = set(arms["control"]), set(arms["disturb"])
        if ci != di:
            bad_pairs.append((key, f"init_state mismatch control={sorted(ci)} disturb={sorted(di)}"))
            continue
        n_pairs += len(ci)
    checks.append(("pair counts: every (task,H,seed) has both arms on identical init states",
                   not bad_pairs, f"{n_pairs} pairs; problems: {bad_pairs if bad_pairs else 'none'}"))

    # check 2: pre-intervention action equality
    act = load_jsonl(bundle / f"actions_pre_iv_{SUCCESS_GATE}.jsonl")
    by_pair = defaultdict(dict)
    for row in act:
        by_pair[(row["task"], row["H"], row["seed"], row["arm"])] = {
            t: a for t, a in (row.get("actions_pre_iv") or []) if a is not None
        }
    worst = 0.0
    worst_key = None
    compared = 0
    for (task, H, seed) in sorted({(k[0], k[1], k[2]) for k in by_pair}):
        c = by_pair.get((task, H, seed, "control"), {})
        d = by_pair.get((task, H, seed, "disturb"), {})
        for t in sorted(set(c) & set(d)):
            l1 = max(abs(x - y) for x, y in zip(c[t], d[t]))
            compared += 1
            if l1 > worst:
                worst, worst_key = l1, (task, H, seed, t)
    checks.append(("pre-intervention equality: control == disturb action-by-action before step %d" % world_step,
                   worst == 0.0, f"{compared} step-pairs compared; max |L1| = {worst:g}"
                                  + (f" at {worst_key}" if worst_key else "")))

    # check 3: stale contract
    stale_bad = []
    for (task, H, seed), arms in sorted(cells.items()):
        for arm, eps_by_state in arms.items():
            for isx, e in sorted(eps_by_state.items()):
                got = e.get("stale_action_steps")
                want = 0 if arm == "control" else H
                if got != want:
                    stale_bad.append((task, H, seed, isx, arm, got, want))
    checks.append(("stale contract: control executes 0 stale actions, disturb executes exactly H",
                   not stale_bad, f"{len(stale_bad)} violations" + (f", e.g. {stale_bad[:3]}" if stale_bad else "")))

    # ------------------------------------------------------- success tables
    w("## 1. Task success (paired, control vs disturbance)")
    w("")
    w(f"Source: `episodes_{SUCCESS_GATE}.jsonl`, {len(eps)} episodes. "
      "Cost = control success − disturbed success. Paired over the SAME init state and seed.")
    w("")
    w("### Per task")
    w("")
    w("| task | H | control | disturb | cost | 95% CI (Wilson, control / disturb) | discordant c→f / f→c | exact McNemar p | n pairs |")
    w("|---|---|---|---|---|---|---|---|---|")
    per_task = {}
    for task in sorted({e["task"] for e in eps}):
        for H in sorted({e["H"] for e in eps}):
            sub = [e for e in eps if e["task"] == task and e["H"] == H]
            ctrl = [e for e in sub if e["arm"] == "control"]
            dist = [e for e in sub if e["arm"] == "disturb"]
            if not ctrl or not dist:
                continue
            nc, nd = len(ctrl), len(dist)
            sc = sum(e["success"] for e in ctrl)
            sd = sum(e["success"] for e in dist)
            # pair by (seed, init_state)
            cmap = {(e["seed"], e["init_state_idx"]): e["success"] for e in ctrl}
            dmap = {(e["seed"], e["init_state_idx"]): e["success"] for e in dist}
            keys = sorted(set(cmap) & set(dmap))
            b = sum(1 for k in keys if cmap[k] and not dmap[k])
            c = sum(1 for k in keys if not cmap[k] and dmap[k])
            p = mcnemar_exact(b, c)
            cl, ch = wilson(sc, nc)
            dl, dh = wilson(sd, nd)
            cost = sc / nc - sd / nd
            per_task[(task, H)] = (sc, nc, sd, nd, cost, len(keys))
            w(f"| {task} | {H} | {sc}/{nc} = {sc/nc:.2f} | {sd}/{nd} = {sd/nd:.2f} | "
              f"{cost:+.2f} | {cl:.2f}–{ch:.2f} / {dl:.2f}–{dh:.2f} | {b} / {c} | {p:.3f} | {len(keys)} |")
    w("")
    w("### Pooled over tasks")
    w("")
    w("| H | control | disturb | cost | n pairs |")
    w("|---|---|---|---|---|")
    pooled = {}
    for H in sorted({e["H"] for e in eps}):
        sub = [e for e in eps if e["H"] == H]
        ctrl = [e for e in sub if e["arm"] == "control"]
        dist = [e for e in sub if e["arm"] == "disturb"]
        sc, nc = sum(e["success"] for e in ctrl), len(ctrl)
        sd, nd = sum(e["success"] for e in dist), len(dist)
        pooled[H] = (sc, nc, sd, nd)
        w(f"| {H} | {sc}/{nc} = {sc/nc:.2f} | {sd}/{nd} = {sd/nd:.2f} | {sc/nc - sd/nd:+.2f} | {min(nc, nd)} |")
    w("")
    costs = [pooled[H][0] / pooled[H][1] - pooled[H][2] / pooled[H][3] for H in sorted(pooled)]
    monotone = all(b >= a for a, b in zip(costs, costs[1:])) or all(b <= a for a, b in zip(costs, costs[1:]))
    w(f"Pooled cost by H: " + ", ".join(f"H={H} {c:+.2f}" for H, c in zip(sorted(pooled), costs)) + ".")
    w("")
    w("**Reading.** " + ("The pooled cost is monotone in H." if monotone else
        "The pooled cost is **not monotone** in H: the data show **no detected monotone effect** "
        "and are **underpowered to rule out modest effects** (they are not evidence of no effect). "
        "At n=10 per cell the binomial noise floor is roughly ±0.25, and resolving a 0.10 difference "
        "at 80% power needs ~300 episodes per arm."))
    w("")

    # ------------------------------------------------------------- stale table
    w("## 2. Protocol contract (not a model property)")
    w("")
    w("`stale_action_steps` counts executed actions chosen for the pre-change world. It is a")
    w("**runner contract** — the intervention lands right after planning and replanning is")
    w("forbidden until the chunk ends — so `== H` is a property of the harness, not of FastWAM.")
    w("")
    w("| H | disturbed episodes with stale == H | control episodes with stale == 0 |")
    w("|---|---|---|")
    for H in sorted({e["H"] for e in eps}):
        d = [e for e in eps if e["H"] == H and e["arm"] == "disturb"]
        c = [e for e in eps if e["H"] == H and e["arm"] == "control"]
        w(f"| {H} | {sum(1 for e in d if e['stale_action_steps'] == H)}/{len(d)} | "
          f"{sum(1 for e in c if e['stale_action_steps'] == 0)}/{len(c)} |")
    w("")

    # ------------------------------------------------------------------ PSNR
    clips = load_jsonl(bundle / f"clips_{CANONICAL_PSNR_GATE}.jsonl")
    psnr_eps = load_jsonl(bundle / f"episodes_{CANONICAL_PSNR_GATE}.jsonl")
    w("## 3. World-model prediction (PSNR), clip-isolated at a matched lag")
    w("")
    w("Source: `clips_%s.jsonl`. Only the clip **planned at step %d** is scored: it is planned"
      " immediately before the displacement, so the plan itself is identical in both arms and the"
      " only difference is the world change. Frame index i corresponds to environment lag"
      " %d*i (video stride)." % (CANONICAL_PSNR_GATE, world_step, stride))
    w("")

    iv = [c for c in clips if c.get("clip_start_step") == world_step]
    by_arm = defaultdict(dict)  # (H, arm) -> {(seed, init_state): {lag: psnr}}
    for c in iv:
        by_arm[(c["H"], c["arm"])][(c["seed"], c["init_state_idx"])] = lag_map(c.get("frame_psnr"))
    lags = sorted({lag for v in by_arm.values() for fm in v.values() for lag in fm})

    w("| H | lag (steps) | control dB | disturb dB | per-pair Δ dB | 95% CI (cluster: init state) | Δ MSE (8-bit²) | n pairs |")
    w("|---|---|---|---|---|---|---|---|")
    canon = {}
    for H in sorted({k[0] for k in by_arm}):
        ctrl = by_arm.get((H, "control"), {})
        dist = by_arm.get((H, "disturb"), {})
        for lag in lags:
            keys = [k for k in sorted(set(ctrl) & set(dist)) if lag in ctrl[k] and lag in dist[k]]
            if not keys:
                continue
            cm = sum(ctrl[k][lag] for k in keys) / len(keys)
            dm = sum(dist[k][lag] for k in keys) / len(keys)
            deltas = {k: [dist[k][lag] - ctrl[k][lag]] for k in keys}
            dmean = sum(v[0] for v in deltas.values()) / len(keys)
            by_state = defaultdict(list)
            for k in keys:
                by_state[k[1]].extend(deltas[k])
            lo, hi = cluster_bootstrap(by_state)
            dmse = db_to_mse(dm) - db_to_mse(cm)
            canon[(H, lag)] = dict(ctrl=cm, dist=dm, delta=dmean, lo=lo, hi=hi, n=len(keys), dmse=dmse)
            w(f"| {H} | {lag * stride} | {cm:.2f} | {dm:.2f} | {dmean:+.2f} | "
              f"{lo:+.2f} … {hi:+.2f} | {dmse:+.1f} | {len(keys)} |")
    w("")

    # the two numbers the earlier drafts quoted, from the same rows
    w("### The retracted comparisons, recomputed from the same rows")
    w("")
    ep_means = defaultdict(dict)
    for e in psnr_eps:
        ep_means[(e["H"], e["arm"])][(e["seed"], e["init_state_idx"])] = e.get("episode_mean_psnr")
    w("**Episode-mean PSNR** (the original \"4.7x\"): averaging frame k over *every* clip in an"
      " episode dilutes the one damaged clip by 1/n_clips, and n_clips ≈ total_steps/H differs"
      " ~10x between H=1 and H=10. This is the dilution confound, not a horizon effect.")
    w("")
    w("| H | control | disturb | Δ dB |")
    w("|---|---|---|---|")
    for H in sorted({k[0] for k in ep_means}):
        c = [v for v in ep_means.get((H, "control"), {}).values() if v is not None]
        d = [v for v in ep_means.get((H, "disturb"), {}).values() if v is not None]
        if not c or not d:
            continue
        w(f"| {H} | {sum(c)/len(c):.2f} | {sum(d)/len(d):.2f} | {sum(d)/len(d) - sum(c)/len(c):+.2f} |")
    w("")
    w("**Per-episode clip average** (the intermediate \"−0.64 vs −1.52, 2.4x\"): this averages"
      " frame k across all clips of an episode instead of isolating the intervention clip, which"
      " reintroduces the same dilution. Compare the table above: clip-isolated, the cost is"
      " **−4.42 dB at H=5 and −4.40 dB at H=10** — roughly 3x larger in absolute terms and with no"
      " H dependence.")
    w("")

    # control lookahead curve
    w("### Control lookahead curve (no intervention at all)")
    w("")
    w("Mean frame PSNR of the *control* arm's intervention clip by lag. This is the no-intervention"
      " baseline: the model is accurate at the moment of planning and drifts inside one committed"
      " chunk. It is a property of the model, and needs no disturbance to show.")
    w("")
    w("| lag (steps) | control dB | n |")
    w("|---|---|---|")
    for H in sorted({k[0] for k in by_arm}):
        pass
    for lag in lags:
        vals = []
        for H in sorted({k[0] for k in by_arm}):
            for fm in by_arm.get((H, "control"), {}).values():
                if lag in fm:
                    vals.append(fm[lag])
        if vals:
            w(f"| {lag * stride} | {sum(vals)/len(vals):.2f} | {len(vals)} |")
    w("")

    # check 4: PSNR pairing
    psnr_bad = []
    for (H, arm), v in by_arm.items():
        pass
    for H in sorted({k[0] for k in by_arm}):
        c, d = by_arm.get((H, "control"), {}), by_arm.get((H, "disturb"), {})
        if set(c) != set(d):
            psnr_bad.append((H, sorted(set(c) ^ set(d))))
    checks.append(("PSNR pairing: both arms present on identical (seed, init_state) for every H",
                   not psnr_bad, f"problems: {psnr_bad if psnr_bad else 'none'}"))

    # ------------------------------------------------------------------- what it means
    w("## 4. What the PSNR number does and does not measure")
    w("")
    w("The displacement is applied **after** the clip was planned and is unobservable until the next")
    w("replan. A predictor whose future was generated before that exogenous change must disagree with")
    w("the realized rollout even if its learned dynamics are perfect. The −4.4 dB therefore measures")
    w("**counterfactual forecast invalidation under an unannounced intervention**.")
    w("")
    w("| # | quantity | measured here? |")
    w("|---|---|---|")
    w("| i | pre-intervention prediction fidelity | yes — lag-0 delta is 0.00 dB by construction; the control lookahead curve is the no-intervention baseline |")
    w("| ii | induced surprise after the change | yes — the lag-4 delta |")
    w("| iii | mismatch detection | no — nothing in this run reads PSNR to trigger a replan |")
    w("| iv | post-replan prediction / action quality | no — the scored clips were planned before the strike |")
    w("| v | task recovery | no — that is the task-success arm (§1) and Gates 13B–13D |")
    w("")
    w("`stale_action_steps == H` is a runner contract (§2), not a learned property.")
    w("")
    w("Note on the metric: PSNR is a log measure, so dB differences are reported next to ΔMSE in")
    w("8-bit units² (`MSE = 255²/10^(PSNR/10)`, the harness convention at")
    w("`eval_libero_single.py:_clip_frame_psnr`). A last-frame/persistence predictor is **not**")
    w("included: the bundle keeps per-frame PSNR, not frames, so it cannot be computed here. That")
    w("remains an open item (Gate 14B).")
    w("")

    # ------------------------------------------------------------------ checks
    w("## 5. Validity checks")
    w("")
    w("| check | result | detail |")
    w("|---|---|---|")
    all_ok = True
    for name, ok, detail in checks:
        all_ok = all_ok and ok
        w(f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |")
    w("")
    w("Pairing unit: **init state**, not episode. LIBERO loads `init_states[trial_idx]`, so episode")
    w("index *is* the init-state index; 2 seeds × 5 trials is 5 distinct init states observed under 2")
    w("RNG realizations, not 10 independent initial states. Confidence intervals therefore resample")
    w("init states (5 clusters), which is the honest unit.")
    w("")

    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwrote {args.out}")
    print("\nAUDIT: " + ("PASS" if all_ok else "FAIL"))
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
